#!/usr/bin/env python3
"""One-time import of the Ryze-hosted blog backup into posts/*.md + static/img/*.webp.

Usage: python3 -I import_ryze.py <cj-blog-backup.json> <cj-blog-images.json>
"""
import base64, io, json, pathlib, re, sys
from bs4 import BeautifulSoup
from PIL import Image
import yaml

ROOT = pathlib.Path(__file__).parent
POSTS, IMG = ROOT / "posts", ROOT / "static" / "img"
BLOG = "https://blog.candjpropertyassessments.com"


def main(backup_path, images_path):
    backup = json.loads(pathlib.Path(backup_path).read_text(encoding="utf-8"))
    images = json.loads(pathlib.Path(images_path).read_text(encoding="utf-8"))["images"]
    POSTS.mkdir(exist_ok=True); IMG.mkdir(parents=True, exist_ok=True)
    done, skipped = 0, []
    for art in backup["articles"]:
        slug = art["slug"].strip("/")
        if not slug:
            continue  # homepage is regenerated by build.py
        full = BeautifulSoup(art["full_html"], "html.parser")
        soup = BeautifulSoup(art["article_html"], "html.parser")

        # FAQ + dates from the JSON-LD Ryze emitted
        faq, published, modified = [], "", ""
        for raw in art.get("jsonld", []):
            try:
                data = json.loads(raw)
            except ValueError:
                continue
            for item in (data if isinstance(data, list) else data.get("@graph", [data])):
                t = item.get("@type")
                if t == "FAQPage":
                    for q in item.get("mainEntity", []):
                        a = q.get("acceptedAnswer", {}).get("text", "")
                        faq.append({"q": q.get("name", "").strip(), "a": BeautifulSoup(a, "html.parser").get_text(" ", strip=True)})
                elif t in ("BlogPosting", "Article", "NewsArticle"):
                    published = published or item.get("datePublished", "")
                    modified = modified or item.get("dateModified", "")
        published = (art.get("published") or published or "")[:10]
        modified = (modified or published)[:10]
        if not published:
            tm = full.find("time")
            published = (tm.get("datetime", "") if tm else "")[:10]
        if not published:
            skipped.append(slug); continue

        # Drop Ryze widgets: H1 (rebuilt), CTA boxes, FAQ accordion (rebuilt from JSON-LD)
        for h1 in soup.find_all("h1"):
            h1.decompose()
        for div in soup.find_all("div", recursive=False):
            text = div.get_text(" ", strip=True)
            if div.find("a", string=re.compile("quote", re.I)) and len(text) < 400:
                div.decompose()
            elif faq and any(f["q"][:40] in text for f in faq[:2]):
                div.decompose()
            elif text.upper().startswith("TL;DR"):
                div.name = "aside"
        # Trailing "FAQ" heading left without content
        last = [c for c in soup.contents if getattr(c, "name", None)]
        if last and last[-1].name in ("h2", "h3") and "question" in last[-1].get_text().lower():
            last[-1].decompose()

        # Re-host images as WebP
        for n, img in enumerate(soup.find_all("img"), 1):
            src = img.get("src", "")
            absolute = src if src.startswith("http") else BLOG + "/" + src.lstrip("/")
            data_url = images.get(absolute) or images.get(src)
            if not data_url:
                img.decompose(); continue
            raw = base64.b64decode(data_url.split(",", 1)[1])
            im = Image.open(io.BytesIO(raw)).convert("RGB")
            if im.width > 1400:
                im = im.resize((1400, round(im.height * 1400 / im.width)))
            name = f"{slug}-{n}.webp"
            im.save(IMG / name, "WEBP", quality=80)
            for attr in list(img.attrs):
                if attr not in ("alt",):
                    del img[attr]
            img["src"] = f"/static/img/{name}"; img["loading"] = "lazy"
            img["width"], img["height"] = str(im.width), str(im.height)

        # Strip Tailwind classes / inline styles; keep links relative for the blog
        for tag in soup.find_all(True):
            for attr in ("class", "style", "id"):
                tag.attrs.pop(attr, None)
            if tag.name == "a" and tag.get("href", "").startswith(BLOG):
                tag["href"] = tag["href"][len(BLOG):] or "/"

        title = (art.get("h1") or art.get("title") or slug).strip()
        fm = {"title": title, "description": art.get("meta_description", "").strip(), "date": published,
              "updated": modified, "slug": slug, "keywords": [], "source": "ryze-import"}
        if faq:
            fm["faq"] = faq
        body = str(soup).strip()
        (POSTS / f"{slug}.md").write_text("---\n" + yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=1000)
                                         + "---\n\n" + body + "\n", encoding="utf-8")
        done += 1
    print(f"imported {done} posts; skipped (no date): {skipped}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
